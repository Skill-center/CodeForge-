import { startBench } from './harness';

declare const __BENCH_ENGINE_VERSION__: string;

function stubCompletions(context: CompletionContext): CompletionResult | null {
  const word = context.matchBefore(/\w*/);
  if (!word || (word.from === word.to && !context.explicit)) return null;
  return { from: word.from, options: STUB_COMPLETIONS.map((label) => ({ label, type: 'keyword' })) };
}

function extensions(language: BenchLanguage): Extension[] {
  return [
    lineNumbers(),
    highlightActiveLineGutter(),
    highlightSpecialChars(),
    history(),
    foldGutter(),
    drawSelection(),
    dropCursor(),
    EditorState.allowMultipleSelections.of(true),
    indentOnInput(),
    bracketMatching(),
    closeBrackets(),
    autocompletion({ override: [stubCompletions], activateOnTyping: false }),
    rectangularSelection(),
    cursorLineHighlight(),
    highlightSelectionMatches(),
    search({ top: true }),
    keymap.of([...closeBracketsKeymap, ...defaultKeymap, ...searchKeymap, ...historyKeymap, ...foldKeymap, indentWithTab]),
    languageExtension(language),
    forgeTheme(DEFAULT_PALETTE),
    fontSizeTheme(14),
    EditorState.tabSize.of(4),
    EditorView.contentAttributes.of({
      autocorrect: 'off',
      autocapitalize: 'off',
      spellcheck: 'false',
      autocomplete: 'off',
      'aria-label': 'Code editor',
    }),
  ];
}

class CodeMirrorBench implements BenchEngine {
  readonly id = 'codemirror' as const;
  readonly version = __BENCH_ENGINE_VERSION__;
  private view: EditorView | null = null;

  private get v(): EditorView {
    if (!this.view) throw new Error('the editor is not mounted');
    return this.view;
  }

  mount(parent: HTMLElement): void {
    this.view = new EditorView({ parent, state: EditorState.create({ doc: '', extensions: extensions('plaintext') }) });
  }

  setDocument(text: string, language: BenchLanguage): void {
    this.v.setState(EditorState.create({ doc: text, extensions: extensions(language) }));
    this.v.scrollDOM.scrollTop = 0;
  }

  text(): string {
    return this.v.state.doc.toString();
  }

  focus(): void {
    this.v.focus();
  }

  setCursor(offset: number): void {
    this.v.dispatch({ selection: { anchor: Math.min(offset, this.v.state.doc.length) }, scrollIntoView: true });
  }

  type(text: string): void {
    // The same route as DOM text input: input handlers (closeBrackets and
    // friends) first, then a plain replacement marked as typing.
    const view = this.v;
    const { from, to } = view.state.selection.main;
    const insert = () => view.state.update(view.state.replaceSelection(text), { userEvent: 'input.type' });
    const handled = view.state.facet(EditorView.inputHandler).some((handler) => handler(view, from, to, text, insert));
    if (!handled) view.dispatch(insert(), { scrollIntoView: true });
  }

  scrollTop(): number {
    return this.v.scrollDOM.scrollTop;
  }

  setScrollTop(px: number): void {
    this.v.scrollDOM.scrollTop = px;
  }

  scrollMax(): number {
    const scroller = this.v.scrollDOM;
    return scroller.scrollHeight - scroller.clientHeight;
  }

  highlightedSpans(): number {
    // HighlightStyle classes are generated by style-mod and start with "ͼ".
    let count = 0;
    for (const span of Array.from(this.v.contentDOM.querySelectorAll('.cm-line span'))) {
      if (/(^|\s)ͼ/.test(span.className)) count += 1;
    }
    return count;
  }

  async replaceAll(searchText: string, replaceText: string): Promise<boolean> {
    const view = this.v;
    openSearchPanel(view);
    view.dispatch({ effects: setSearchQuery.of(new SearchQuery({ search: searchText, replace: replaceText })) });
    const before = view.state.doc.toString();
    replaceAll(view);
    const changed = view.state.doc.toString() !== before;
    closeSearchPanel(view);
    return changed;
  }

  async showCompletion(): Promise<boolean> {
    const view = this.v;
    startCompletion(view);
    const start = performance.now();
    while (performance.now() - start < 1500) {
      if (completionStatus(view.state) === 'active' && view.dom.querySelector('.cm-tooltip-autocomplete')) return true;
      await new Promise((resolve) => requestAnimationFrame(resolve));
    }
    return false;
  }

  closeCompletion(): void {
    closeCompletion(this.v);
  }

  inputRoot(): HTMLElement {
    return this.v.dom;
  }

  inputMode(): string {
    return (this.v.contentDOM as HTMLElement & { editContext?: unknown }).editContext ? 'editcontext' : 'contenteditable';
  }
}

void startBench(new CodeMirrorBench());
